function translateForNode(node,value) {
  if(!isMotionNode(node)) return translate(value);
  const element=node.nodeType===Node.TEXT_NODE?node.parentElement:node;
  if(element?.closest('.tm-user-copy,.tm-slot>small')) return value;
  if(element?.closest('.tw-upload-hint')?.parentElement.querySelector('input')?.files?.length) return value;
  const field=element?.closest('.cm-select-field');
  const select=field?.querySelector('select');
  if(select?.matches('[data-tm-source],#ts-project,#ts-target') &&
    ((element.tagName==='OPTION' && element.value) || element.closest('li:not(:first-child)') || (select.value && element.closest('summary')))) return value;
  return ToolMotion.uiLabel(translate(ToolMotion.uiLabel(value)));
}
function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (node.parentElement?.closest('script,style,textarea,[contenteditable=true]')) return;
    const result = translateForNode(node,node.data);
    if (result !== node.data) {
      const option = node.parentElement;
      if (option?.tagName === 'OPTION' && !option.hasAttribute('value')) option.value = option.textContent;
      node.data = result;
    }
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const attr of ['placeholder','aria-label','title','alt']) {
    const raw = node.getAttribute(attr);
    if (raw) { const result = translateForNode(node,raw); if (result !== raw) node.setAttribute(attr,result); }
  }
}
function localize(root) {
  translateNode(root);
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const walker = document.createTreeWalker(root,NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  while (walker.nextNode()) translateNode(walker.currentNode);
}
for (const id of ['site','site-modal','site-toasts']) {
  const root=document.getElementById(id);
  if (!root) continue;
  new MutationObserver(changes=>{
    for(const change of changes) {
      if(change.type==='childList') change.addedNodes.forEach(localize);
      else translateNode(change.target);
    }
  }).observe(root,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:['placeholder','aria-label','title','alt']});
  localize(root);
}
