function translate(value) {
  const key = value.trim();
  if (!/[\u3400-\u9fff]/.test(key)) return value;
  let result = labels[key];
  if (!result) {
    for (const [pattern, replacement] of rules) {
      if (pattern.test(key)) { result = key.replace(pattern, replacement); break; }
    }
  }
  if (!result) {
    // "Label: value" pairs are translated on each side.
    const parts = key.match(/^([^:：]{1,60})[:：]\s*(.+)$/);
    if (parts) {
      const head = translate(parts[1]), tail = translate(parts[2]);
      if (head !== parts[1] || tail !== parts[2]) result = head + ': ' + tail;
    }
  }
  if (result && /[\u3400-\u9fff]/.test(result)) {
    // Names captured by a rule keep translating, so no Chinese leaks through.
    result = result.replace(/[^\s·,;:—–-]+/g, part => /[\u3400-\u9fff]/.test(part) ? translate(part) : part);
  }
  return result ? value.replace(key, () => result) : value;
}
